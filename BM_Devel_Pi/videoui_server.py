NET_MODE_FILE = "/run/bmcam_net/mode"


def net_mode(path=None):
    try:
        with open(path or NET_MODE_FILE, "r", encoding="utf-8") as f:
            return f.read().strip()
    except OSError:
        return None


def open_ap_banner(mode):
    """The open-network notice (D-S16-6), shown while the AP is up."""
