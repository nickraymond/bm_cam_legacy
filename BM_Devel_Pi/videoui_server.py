"""
Sprint15 video gallery/download server. stdlib http.server ONLY — no
framework, no pip installs, no database: manifest.json IS the state,
regenerated by video_manifest at every clip boundary.

Routes:
  /                  the gallery page (single static HTML, inline JS)
  /manifest.json     the clip list (newest first)
  /videos/<name>     clip MP4s and poster JPEGs, with single-range HTTP
                     Range support (iPhone Safari scrubbing needs 206s)

Serving rules (defensive, the unit may sit on an open AP later):
  - only basenames, only .mp4/.jpg, only inside the video directory
  - no directory listings, no dotfiles, GET/HEAD only

Runs as a daemon thread of the video runtime when video.ui.enabled
(default port 8080); binds 0.0.0.0 so it serves the LAN today and the
`wap` AP later without change.
"""

